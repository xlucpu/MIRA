library(MIRA)
e <- mira_example()
x <- e$expression
p <- predict_mira(x, e$batch_id)
same <- function(a,b) isTRUE(all.equal(a,b,tolerance=1e-12,check.attributes=FALSE))
stopifnot(identical(p$predicted_label,e$expected$predicted_label),
          same(p$p_C1,e$expected$p_C1),same(p$p_C1a_given_C1,e$expected$p_C1a_given_C1))
for(f in list(predict_MIRA,predict_MIRA_v2,predict_MIRA_final))stopifnot(identical(f(x,e$batch_id),p))
r <- predict_mira(x[nrow(x):1,ncol(x):1],e$batch_id)
i <- match(p$sample_id,r$sample_id)
stopifnot(identical(p$predicted_label,r$predicted_label[i]),same(p$p_C1,r$p_C1[i]))
b <- setNames(rep(c("A","B"),each=6),colnames(x))
a <- predict_mira(x,b)
z <- predict_mira(x,b[12:1])
stopifnot(identical(a,z))
split <- do.call(rbind,lapply(c("A","B"),function(batch)predict_mira(x[,b==batch,drop=FALSE],batch)))
stopifnot(identical(a$predicted_label,split$predicted_label),same(a$p_C1,split$p_C1))
stopifnot(identical(predict_mira(log1p(x),e$batch_id),p))
stopifnot(identical(predict_mira(rbind(x,unused=NA_real_),e$batch_id),p))
stopifnot(identical(MIRA:::mira_two_step_labels(c(.5,.5,.499),c(.5,.499,1)),c("C1a","C1b","C2")))
bad <- function(expr,pattern) {err<-tryCatch({force(expr);NULL},error=function(e)conditionMessage(e));stopifnot(!is.null(err),grepl(pattern,err,ignore.case=TRUE))}
bad(predict_mira(x[-1,],e$batch_id),"Missing")
q<-x;rownames(q)[1]<-rownames(q)[2];bad(predict_mira(q,e$batch_id),"Unique")
q<-x;colnames(q)[1]<-colnames(q)[2];bad(predict_mira(q,e$batch_id),"Unique")
q<-x;q[1,1]<-Inf;bad(predict_mira(q,e$batch_id),"finite")
bad(predict_mira(x),"batch_id")
bad(predict_mira(x[,1,drop=FALSE],e$batch_id),"two samples")
bad(predict_mira(x,c("one",rep("rest",11))),"two samples")
m<-mira_model();stopifnot(length(m$gene_universe)==18686L,length(m$mhc_genes)==8L,length(m$b_genes)==8L)
stopifnot(!any(c("training_ids","training_labels","training_weights","gate_fit","branch_fit")%in%names(m)))
m$thresholds[1]<-.4;bad(predict_mira(x,e$batch_id,model=m),"specification")
old<-predict_mira(x,e$batch_id,decision_rule="legacy_joint_argmax")
stopifnot(all(old$decision_rule=="legacy_joint_argmax"),grepl("historical",attr(old,"probability_note")))
stopifnot(!"glmnet"%in%loadedNamespaces(),!"Matrix"%in%loadedNamespaces())

